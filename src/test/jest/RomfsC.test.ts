/**
 * generateRomfsC 必须与 tools/mkromfs_for_honeygui.py 的 C 输出逐字节一致：
 * 浏览器版没有 Python，用它代替脚本生成 app_romfs.c，输出不同会让仿真行为与桌面版分叉。
 */
import { generateRomfsC, romfsRootName } from '../../simulation/RomfsC';

function filesOf(entries: Record<string, number[]>): Map<string, Uint8Array> {
  return new Map(Object.entries(entries).map(([name, bytes]) => [name, Uint8Array.from(bytes)]));
}

describe('generateRomfsC', () => {
  it('writes a file entry with hex bytes and the root dirent', () => {
    const c = generateRomfsC(filesOf({ 'a.bin': [0, 1, 255] }), 'app_romfs_root');
    expect(c).toBe(
`/* Generated by mkromfs. Edit with caution. */
#include "hg_romfs.h"

static const uint8_t _romfs_root_a_bin[] = {
0x00,0x01,0xff
};

static const struct romfs_dirent _romfs_root[] = {
    {ROMFS_DIRENT_FILE, "a.bin", (uint8_t *)_romfs_root_a_bin, sizeof(_romfs_root_a_bin)/sizeof(_romfs_root_a_bin[0])}
};

const struct romfs_dirent app_romfs_root = {
    ROMFS_DIRENT_DIR, "/", (uint8_t *)_romfs_root, sizeof(_romfs_root)/sizeof(_romfs_root[0])
};
`);
  });

  it('turns names into identifiers: special characters become underscores, a leading digit gets _f_', () => {
    const c = generateRomfsC(filesOf({ '1abc.bin': [1], 'a-b c.png': [2] }), 'r');
    expect(c).toContain('_romfs_root_a_b_c_png[]');
    expect(c).toContain('_romfs_root_f_1abc_bin[]');
    // the string stored in the dirent keeps the real file name
    expect(c).toContain('"a-b c.png"');
  });

  it('sorts children by code point and groups files into nested folders', () => {
    const c = generateRomfsC(filesOf({ 'b.bin': [1], 'B.bin': [2], 'dir/inner.bin': [3], '_u.bin': [4] }), 'r');
    const order = ['"B.bin"', '"_u.bin"', '"b.bin"', '"dir"'].map(s => c.indexOf(`ROMFS_DIRENT_${s === '"dir"' ? 'DIR' : 'FILE'}, ${s}`));
    expect(order.every(i => i >= 0)).toBe(true);
    expect([...order].sort((x, y) => x - y)).toEqual(order);
    expect(c).toContain('static const struct romfs_dirent _romfs_root_dir[] = {');
  });

  it('keeps empty files as an empty brace initializer', () => {
    const c = generateRomfsC(filesOf({ 'empty.bin': [] }), 'r');
    expect(c).toContain('static const uint8_t _romfs_root_empty_bin[] = {\n\n};');
  });
});

describe('romfsRootName', () => {
  it('derives the root variable from the output file name', () => {
    expect(romfsRootName('app_romfs.c')).toBe('app_romfs_root');
    expect(romfsRootName('C:\\build\\my-app.c')).toBe('my_app_root');
    expect(romfsRootName('/tmp/a b.c')).toBe('a_b_root');
  });
});
