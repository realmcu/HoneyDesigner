describe('shared elements', () => {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { collectSharedElementPairs, orientPair } = require('../../shared/sharedElement');
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { collectViewTransitionSharedPairs, generateViewTransitionSource } = require('../../codegen/honeygui/files/ViewTransitionGenerator');

  const components = [
    { id: 'v1', name: 'transition_index', type: 'hg_view', data: {} },
    { id: 'c1', name: 'card_depth', type: 'hg_rect', parent: 'v1', data: { sharedTag: 'cover' } },
    { id: 'c1b', name: 'other', type: 'hg_rect', parent: 'v1', data: { sharedTag: 'unpaired' } },
    { id: 'v2', name: 'tr_depth', type: 'hg_view', data: {} },
    { id: 'c2', name: 'hero_depth', type: 'hg_rect', parent: 'v2', data: { sharedTag: 'cover' } },
  ];

  it('pairs tags across pages only and can be oriented', () => {
    const pairs = collectSharedElementPairs(components);
    expect(pairs).toHaveLength(1);
    expect(pairs[0].tag).toBe('cover');
    expect(orientPair(pairs[0], 'v2').from.component.id).toBe('c2');
    expect(orientPair(pairs[0], 'nope')).toBeNull();
  });

  it('emits the lookup table and the flight, and stubs when there is none', () => {
    const withPairs = generateViewTransitionSource(collectViewTransitionSharedPairs(components));
    expect(withPairs).toContain('{ "cover", "transition_index", "card_depth", "tr_depth", "hero_depth" },');
    expect(withPairs).toContain('hg_vt_hero_begin(from, to, target);');
    expect(withPairs).toContain('static void hg_vt_hero_cb(');
    const withoutPairs = generateViewTransitionSource([]);
    expect(withoutPairs).not.toContain('hg_vt_hero_cb');
    expect(withoutPairs).toContain('static void hg_vt_hero_release_source(void)');
  });
});

describe('per-element stagger', () => {
  it('gives every child its own slice, back to front', () => {
    const profile = VIEW_TRANSITION_PROFILES.SWITCH_IN_DEPTH_ZOOM;
    const stagger = profile.stagger!;
    expect(stagger.step).toBeGreaterThan(0);
    // 第一个孩子早就进场，最后一个明显更晚
    const room = 1 - stagger.start - stagger.window;
    const step = Math.min(stagger.step, room / 5);
    expect(transitionCurveAt('easeOut', windowProgress(stagger.start, [stagger.start, stagger.start + stagger.window]))).toBe(0);
    expect(transitionCurveAt('easeOut', windowProgress(stagger.start + step * 5, [stagger.start, stagger.start + stagger.window]))).toBeGreaterThan(0.5);
    // 圆形揭示等圆铺开后再进子控件
    expect(VIEW_TRANSITION_PROFILES.SWITCH_IN_CIRCLE_REVEAL.stagger!.start).toBeGreaterThanOrEqual(0.5);
  });
});
