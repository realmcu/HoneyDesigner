describe('readViewTransition', () => {
  it('recognises the presets and the unsupported zoom-fade aliases', () => {
    expect(readViewTransition('SWITCH_IN_SHEET_UP')).toBe('SWITCH_IN_SHEET_UP');
    expect(readViewTransition('SWITCH_IN_CENTER_ZOOM_FADE')).toBe('SWITCH_IN_DEPTH_ZOOM');
    expect(readViewTransition('SWITCH_IN_ANIMATION_CENTER_ZOOM_FADE')).toBe('SWITCH_IN_DEPTH_ZOOM');
    expect(readViewTransition('SWITCH_IN_ANIMATION_FADE')).toBeNull();
    expect(readViewTransition(undefined)).toBeNull();
  });

  it('shows the alias as depth zoom in the selects', () => {
    expect(normalizeSwitchInStyle('SWITCH_IN_CENTER_ZOOM_FADE')).toBe('SWITCH_IN_DEPTH_ZOOM');
    expect(normalizeSwitchInStyle('SWITCH_IN_ANIMATION_FADE')).toBe('SWITCH_IN_ANIMATION_FADE');
    const values = SWITCH_IN_STYLES.map(s => s.value);
    expect(values).toEqual(expect.arrayContaining(['SWITCH_IN_DEPTH_ZOOM', 'SWITCH_IN_SHEET_UP', 'SWITCH_IN_CIRCLE_REVEAL']));
    expect(values).not.toContain('SWITCH_IN_CENTER_ZOOM_FADE');
  });
});

describe('transition curves', () => {
  it('starts and ends at rest', () => {
    for (const profile of Object.values(VIEW_TRANSITION_PROFILES)) {
      const start = viewTransitionFrameAt(profile, 0);
      const end = viewTransitionFrameAt(profile, 1);
      expect(start.fromScale).toBe(1);
      expect(start.fromOpacity).toBe(1);
      expect(start.toScale).toBeCloseTo(profile.toScale);
      expect(end.toScale).toBeCloseTo(1);
      expect(end.toOpacity).toBeCloseTo(1);
      expect(end.toOffsetY).toBeCloseTo(0);
      expect(end.fromScale).toBeCloseTo(profile.fromScale);
    }
  });

  it('springs into place on entry', () => {
    const spring = Array.from({ length: 201 }, (_, i) => transitionCurveAt('spring', i / 200));
    expect(spring[0]).toBe(0);
    expect(spring[200]).toBe(1);
    const peak = Math.max(...spring);
    // 只过冲一次，约 8%
    expect(peak).toBeGreaterThan(1.05);
    expect(peak).toBeLessThan(1.1);
    expect(transitionCurveAt('spring', 0.4)).toBeGreaterThan(0.85);
  });

  it('overshoots a little for the bottom sheet', () => {
    const peak = Math.max(...Array.from({ length: 101 }, (_, i) => transitionCurveAt('easeOutBack', i / 100)));
    expect(peak).toBeGreaterThan(1);
    expect(peak).toBeLessThan(1.25);
    // 回弹时新页略越过终点（向上冒一点）
    const sheet = VIEW_TRANSITION_PROFILES.SWITCH_IN_SHEET_UP;
    expect(Math.min(...Array.from({ length: 101 }, (_, i) => viewTransitionFrameAt(sheet, i / 100).toOffsetY))).toBeLessThan(0);
  });

  it('reveals the circle before fading the content in', () => {
    const circle = VIEW_TRANSITION_PROFILES.SWITCH_IN_CIRCLE_REVEAL;
    expect(viewTransitionFrameAt(circle, 0.5).toOpacity).toBe(0);
    expect(viewTransitionFrameAt(circle, 0.75).circle).toBeCloseTo(1);
    expect(viewTransitionFrameAt(VIEW_TRANSITION_PROFILES.SWITCH_IN_DEPTH_ZOOM, 0.5).circle).toBe(0);
  });
});

describe('HoneyGUI switch lines', () => {
  it('plays presets through hg_view_transition_switch', () => {
    expect(honeyGuiSwitchViewLine('detail', 'SWITCH_OUT_TO_LEFT_USE_TRANSLATION', 'SWITCH_IN_DEPTH_ZOOM', '    '))
      .toBe('    hg_view_transition_switch("detail", HG_VIEW_TRANSITION_DEPTH_ZOOM);\n');
    expect(honeyGuiSwitchViewLine('detail', undefined, 'SWITCH_IN_CENTER_ZOOM_FADE', ''))
      .toBe('hg_view_transition_switch("detail", HG_VIEW_TRANSITION_DEPTH_ZOOM);\n');
  });

  it('keeps engine styles on gui_view_switch_direct', () => {
    expect(honeyGuiSwitchViewLine('home', undefined, undefined, '  '))
      .toBe('  gui_view_switch_direct(gui_view_get_current(), "home", SWITCH_OUT_TO_LEFT_USE_TRANSLATION, SWITCH_IN_FROM_RIGHT_USE_TRANSLATION);\n');
    expect(honeyGuiSwitchViewLine('home', 'SWITCH_INIT_STATE', 'SWITCH_IN_ANIMATION_FADE', ''))
      .toBe('gui_view_switch_direct(gui_view_get_current(), "home", SWITCH_INIT_STATE, SWITCH_IN_ANIMATION_FADE);\n');
  });

  it('falls back to engine styles for swipe gestures', () => {
    expect(honeyGuiSwitchOnEventStyles('SWITCH_OUT_TO_LEFT_USE_TRANSLATION', 'SWITCH_IN_SHEET_UP'))
      .toEqual({ out: 'SWITCH_INIT_STATE', in: 'SWITCH_IN_FROM_BOTTOM_USE_TRANSLATION' });
    expect(engineSwitchStyles('A', 'SWITCH_IN_CIRCLE_REVEAL')).toEqual({ out: 'SWITCH_INIT_STATE', in: 'SWITCH_IN_ANIMATION_FADE' });
    expect(honeyGuiSwitchOnEventStyles(undefined, undefined))
      .toEqual({ out: 'SWITCH_OUT_TO_LEFT_USE_TRANSLATION', in: 'SWITCH_IN_FROM_RIGHT_USE_TRANSLATION' });
  });
});

describe('HoneyGUI transition runtime', () => {
  it('is only generated when a page uses a preset', () => {
    const used = [{ id: 'b', eventConfigs: [{ actions: [{ type: 'switchView', target: 'x', switchInStyle: 'SWITCH_IN_SHEET_UP' }] }] }];
    expect(usesViewTransition(used)).toBe(true);
    expect(usesViewTransition([{ id: 'b', data: { switchInStyle: 'SWITCH_IN_ANIMATION_FADE' } }])).toBe(false);

    const header = AutoGeneratedBindingsGenerator.generateHeader([], true);
    expect(header).toContain('#define HG_VIEW_TRANSITION_SHEET_UP 2');
    expect(header).toContain('void hg_view_transition_switch(const char *target, uint8_t preset);');
    expect(AutoGeneratedBindingsGenerator.generateHeader([], false)).not.toContain('hg_view_transition_switch');
    expect(AutoGeneratedBindingsGenerator.generateSource([], true)).toContain('void hg_view_transition_switch(const char *target, uint8_t preset)');
    expect(AutoGeneratedBindingsGenerator.generateSource([], false)).not.toContain('hg_view_transition_switch');
  });

  it('holds the engine until the animation is over', () => {
    const code = generateViewTransitionSource();
    expect(code).toContain('gui_view_switch_direct(from, target, SWITCH_INIT_STATE, SWITCH_INIT_STATE);');
    expect(code).toContain('view->animate_step = (t >= 1.0f) ? (uint16_t)obj->h : 0U;');
    expect(code).toContain('static const hg_vt_profile_t hg_vt_profiles[3] =');
    expect(code).toContain('{ 420, 0, 2, 0.9400f, 0.6000f, 1.0000f, 1.0000f, 1.0000f, 0.0000f, 1.0000f, 0.0000f, 0.0000f, 0.1200f, 0.0600f, 0.5000f, 16.0000f },');
    // 揭示圆插在新页之前（画在两页之间）
    expect(code).toContain('gui_list_insert_before(&obj->brother_list, &GUI_BASE(hg_vt_circle)->brother_list);');
  });

  it('runs on a frame clock so a slow first frame does not skip the animation', () => {
    const code = generateViewTransitionSource();
    expect(code).toContain('hg_vt_elapsed += (dt > HG_VT_MAX_FRAME_MS) ? HG_VT_MAX_FRAME_MS : dt;');
    // 每帧只走一次时钟：旧页在时由旧页推进，新页读同一个值
    expect(code).toContain('float t = (hg_vt_from != NULL) ? hg_vt_t : hg_vt_advance();');
    expect(code).not.toContain('hg_vt_t0');
  });
});

