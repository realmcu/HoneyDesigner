/**
 * romfs C 源文件生成（tools/mkromfs_for_honeygui.py 的 C 输出模式的 TypeScript 移植）
 *
 * 浏览器版没有 Python，仿真构建需要在页面里把资源目录打包成 app_romfs.c。
 * 纯函数，不依赖 fs / path，输入是「相对路径 → 文件内容」的映射，
 * 与 Python 脚本逐字节一致（由 src/test/jest/RomfsC.test.ts 对照校验）。
 */

export interface RomfsFile {
    name: string;
    data: Uint8Array;
}

interface FolderNode {
    name: string;
    children: Array<FolderNode | RomfsFile>;
}

function isFolder(node: FolderNode | RomfsFile): node is FolderNode {
    return 'children' in node;
}

/** 与 Python 的 str.isalnum 对齐：Unicode 字母/数字都算（ASCII 之外的名字少见，仍保持一致） */
function isAlnum(ch: string): boolean {
    return /^[\p{L}\p{N}]$/u.test(ch);
}

/** 标识符化：非字母数字替换为下划线；首字符不是数字时加 '_' 前缀，否则加 '_f_' */
function cName(name: string): string {
    const sanitized = Array.from(name).map(ch => (isAlnum(ch) ? ch : '_')).join('');
    if (sanitized && !/^\p{N}/u.test(sanitized)) {
        return '_' + sanitized;
    }
    return '_f_' + sanitized;
}

/** Python 按码点比较字符串（sorted 的默认行为），而 JS 的 < 按 UTF-16 码元比较，代理对会不同 */
function compareNames(a: string, b: string): number {
    const ca = Array.from(a);
    const cb = Array.from(b);
    const n = Math.min(ca.length, cb.length);
    for (let i = 0; i < n; i++) {
        const pa = ca[i].codePointAt(0)!;
        const pb = cb[i].codePointAt(0)!;
        if (pa !== pb) {
            return pa < pb ? -1 : 1;
        }
    }
    return ca.length - cb.length;
}

function buildTree(files: Map<string, Uint8Array>): FolderNode {
    const root: FolderNode = { name: 'romfs_root', children: [] };

    for (const [filePath, data] of files) {
        const parts = filePath.split('/').filter(Boolean);
        let node = root;
        for (const dir of parts.slice(0, -1)) {
            let child = node.children.find((c): c is FolderNode => isFolder(c) && c.name === dir);
            if (!child) {
                child = { name: dir, children: [] };
                node.children.push(child);
            }
            node = child;
        }
        node.children.push({ name: parts[parts.length - 1], data });
    }

    const sortNode = (node: FolderNode): void => {
        node.children.sort((x, y) => compareNames(x.name, y.name));
        node.children.forEach(c => { if (isFolder(c)) { sortNode(c); } });
    };
    sortNode(root);
    return root;
}

function fileCData(file: RomfsFile, prefix: string): string {
    const head = `static const uint8_t ${prefix + cName(file.name)}[] = {\n`;
    const hex: string[] = new Array(file.data.length);
    for (let i = 0; i < file.data.length; i++) {
        hex[i] = '0x' + (file.data[i] < 16 ? '0' : '') + file.data[i].toString(16);
    }
    return head + hex.join(',') + '\n};';
}

function folderCData(folder: FolderNode, prefix: string): string {
    const head = `static const struct romfs_dirent ${prefix + cName(folder.name)}[] = {\n`;
    const cpf = prefix + cName(folder.name);
    const body: string[] = [];
    const payload: string[] = [];

    for (const child of folder.children) {
        const type = isFolder(child) ? 'ROMFS_DIRENT_DIR' : 'ROMFS_DIRENT_FILE';
        const data = cpf + cName(child.name);
        body.push(`    {${type}, "${child.name}", (uint8_t *)${data}, sizeof(${data})/sizeof(${data}[0])}`);
        payload.push(isFolder(child) ? folderCData(child, cpf) : fileCData(child, cpf));
    }

    payload.push(head + body.join(',\n') + '\n};');
    return payload.join('\n\n');
}

/**
 * 生成 romfs 的 C 源文件内容。
 * @param files   资源目录下的文件（键为相对路径，使用 '/' 分隔）
 * @param rootName 根变量名（如 'app_romfs_root'）
 */
export function generateRomfsC(files: Map<string, Uint8Array>, rootName: string): string {
    const tree = buildTree(files);
    const rootVar = cName(tree.name);
    return `/* Generated by mkromfs. Edit with caution. */
#include "hg_romfs.h"

${folderCData(tree, '')}

const struct romfs_dirent ${rootName} = {
    ROMFS_DIRENT_DIR, "/", (uint8_t *)${rootVar}, sizeof(${rootVar})/sizeof(${rootVar}[0])
};
`;
}

/** 与 Python 脚本一致：由输出文件名推出根变量名（'app_romfs.c' → 'app_romfs_root'） */
export function romfsRootName(outputFileName: string): string {
    const base = outputFileName.replace(/^.*[\\/]/, '').replace(/\.[^.]*$/, '');
    return Array.from(base).map(ch => (isAlnum(ch) || ch === '_' ? ch : '_')).join('') + '_root';
}
