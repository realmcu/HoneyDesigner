import * as fs from 'fs';
import * as path from 'path';
import { Component } from '../../../hml/types';
import { writeFileIfChanged } from '../../../utils/fileWrite';

export interface UserFunctionStub {
  name: string;
  kind: 'event' | 'message';
}

export interface HmlComponentSource {
  designName: string;
  components: Component[];
}

export class AutoGeneratedBindingsGenerator {
  static generate(srcDir: string, sources: HmlComponentSource[]): string[] {
    const functions = this.collectFunctions(sources);
    const generatedDir = path.join(srcDir, 'generated');
    fs.mkdirSync(generatedDir, { recursive: true });

    const headerFile = path.join(generatedDir, 'auto_generated_bindings.h');
    const sourceFile = path.join(generatedDir, 'auto_generated_bindings.c');

    writeFileIfChanged(headerFile, this.generateHeader(functions));
    writeFileIfChanged(sourceFile, this.generateSource(functions));
    return [headerFile, sourceFile];
  }

  static collectFunctions(sources: HmlComponentSource[]): UserFunctionStub[] {
    const functions = new Map<string, UserFunctionStub>();

    sources.forEach(({ designName, components }) => {
      components.forEach(component => {
        component.eventConfigs?.forEach(eventConfig => {
          const kind = eventConfig.type === 'onMessage' ? 'message' : 'event';
          eventConfig.actions.forEach(action => {
            if (action.type !== 'callFunction' || !action.functionName?.trim()) return;

            const name = action.functionName.trim();
            if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
              throw new Error(`Invalid callFunction name "${name}" in ${designName}.hml`);
            }

            const existing = functions.get(name);
            if (existing && existing.kind !== kind) {
              throw new Error(
                `callFunction "${name}" has conflicting signatures in ${designName}.hml ` +
                `(${existing.kind} vs ${kind})`
              );
            }
            if (!existing) {
              functions.set(name, { name, kind });
            }
          });
        });
      });
    });

    return [...functions.values()].sort((a, b) => a.name.localeCompare(b.name));
  }

  private static generateHeader(functions: UserFunctionStub[]): string {
    let code = `/**
 * AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.
 * Generated from HoneyGUI HML source files by autogen.
 */
#ifndef AUTO_GENERATED_BINDINGS_H
#define AUTO_GENERATED_BINDINGS_H

#include <stdint.h>
#include "gui_api.h"
#include "gui_text.h"
#include "gui_obj_focus.h"

`;

    functions.forEach(fn => {
      code += fn.kind === 'message'
        ? `void ${fn.name}(gui_obj_t *obj, const char *topic, void *data, uint16_t len);\n`
        : `void ${fn.name}(void *obj, gui_event_t *e);\n`;
    });

    code += `\n#endif // AUTO_GENERATED_BINDINGS_H\n`;
    return code;
  }

  private static generateSource(functions: UserFunctionStub[]): string {
    let code = `/**
 * AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.
 * Weak stubs keep HML independently linkable; strong implementations in
 * the user source directory override these symbols.
 */
#include "auto_generated_bindings.h"

`;

    if (functions.length === 0) {
      return code + `/* No HML callFunction actions were found. */\n`;
    }

    functions.forEach(fn => {
      if (fn.kind === 'message') {
        code += `__attribute__((weak)) void ${fn.name}(gui_obj_t *obj, const char *topic, void *data, uint16_t len)\n{\n`;
        code += `    GUI_UNUSED(obj);\n    GUI_UNUSED(topic);\n    GUI_UNUSED(data);\n    GUI_UNUSED(len);\n`;
      } else {
        code += `__attribute__((weak)) void ${fn.name}(void *obj, gui_event_t *e)\n{\n`;
        code += `    GUI_UNUSED(obj);\n    GUI_UNUSED(e);\n`;
      }
      code += `    // TODO: Implement ${fn.name}\n}\n\n`;
    });

    return code;
  }
}
