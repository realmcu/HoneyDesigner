/** 路径规范化比较（统一正斜杠 + 忽略大小写，Windows 盘符/分隔符差异不敏感） */
const normalizePath = (p: string): string => p.replace(/\\/g, '/').toLowerCase();

/** 节点 id：viewKey 复合键（relPath#viewId）；旧数据回退 file#id */
const nodeIdOf = (view: ViewInfo): string => view.viewKey || `${view.file}#${view.id}`;

/** 解析器确定性 fallback id 形如 `${basename}_hg_view_auto_N` / `hg_view_auto_N` */
const isAutoGeneratedId = (id: string): boolean => /(^|_)hg_view_auto_\d+$/.test(id);

/** 真实屏节点判定：missing:/ambiguous: 占位节点不可作为连接端点（T11） */
const isRealViewNodeId = (id: string | null | undefined): boolean =>
  !!id && !id.startsWith('missing:') && !id.startsWith('ambiguous:');

/** 复合键 relPath#viewId → 裸 view id（switchView 的 target 用裸 id） */
const bareViewId = (viewKey: string): string => viewKey.slice(viewKey.indexOf('#') + 1);

/**
 * 从 T2 边数据提取写事务定位键（T11 → T10 applyNavEdit 入参）。
 * 定位字段不齐（旧数据 / 快照缺失）返回 null，编辑操作降级禁用。
 */
const locatorOf = (e: ViewEdgeInfo): NavEditEdgeLocator | null => {
  if (!e.sourceViewKey || !e.sourceControlId
    || typeof e.eventConfigIndex !== 'number' || e.eventConfigIndex < 0
    || typeof e.actionIndex !== 'number' || e.actionIndex < 0
    || (!e.sourceFileHash && typeof e.sourceFileMtime !== 'number')) {
    return null;
  }
  return {
    sourceViewKey: e.sourceViewKey,
    sourceControlId: e.sourceControlId,
    eventType: e.eventType || e.event,
    eventConfigIndex: e.eventConfigIndex,
    actionIndex: e.actionIndex,
    target: e.target,
    sourceIsView: e.sourceIsView,
    sourceIsTimer: e.sourceIsTimer,
    sourceFileMtime: e.sourceFileMtime,
    sourceFileHash: e.sourceFileHash,
  };
};

/** 事件类型 → 本地化标签（复用 event.* i18n key，缺失回退原始值） */
const eventLabel = (type: string): string => {
  const key = `event.${type}`;
  const label = t(key as Parameters<typeof t>[0]);
  return label === key ? type : label;
};

const SWITCH_OUT_DEFAULT = 'SWITCH_OUT_TO_LEFT_USE_TRANSLATION';
const SWITCH_IN_DEFAULT = 'SWITCH_IN_FROM_RIGHT_USE_TRANSLATION';

/** 切换动画枚举值 → 本地化标签（缺失回退默认动画） */
const styleLabel = (
  list: { value: string; labelKey: string }[],
  value: string | undefined,
  fallback: string
): string => {
  const v = value || fallback;
  const found = list.find(s => s.value === v);
  return found ? t(found.labelKey as Parameters<typeof t>[0]) : v;
};

/** 出/入动画组合标签，用于聚焦模式展开的 `触发控件·事件·动画` */
const animationLabelOf = (e: ViewEdgeInfo): string => {
  const out = styleLabel(SWITCH_OUT_STYLES, e.switchOutStyle, SWITCH_OUT_DEFAULT);
  const inn = styleLabel(SWITCH_IN_STYLES, e.switchInStyle, SWITCH_IN_DEFAULT);
  return `${out} → ${inn}`;
};

