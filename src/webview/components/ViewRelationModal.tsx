// ---------------- 图构建 ----------------

interface GraphSeed {
  id: string;
  data: ViewNodeData;
}

interface GraphModel {
  seeds: GraphSeed[]; // 已按种子布局顺序排序（当前文件优先 → 相对路径 → 名称；占位节点殿后）
  edges: ViewFlowEdge[];
  viewCount: number;
  edgeCount: number;
}

const buildGraph = (allViews: ViewInfo[] | undefined, currentFilePath: string | undefined): GraphModel => {
  const views = allViews || [];
  const cur = currentFilePath ? normalizePath(currentFilePath) : '';

  const isCurrentFile = (v: ViewInfo): boolean => {
    if (!cur) {
      return false;
    }
    if (v.filePath) {
      return normalizePath(v.filePath) === cur;
    }
    // 旧数据无绝对路径：回退 basename 比较
    const base = (cur.split('/').pop() || '').replace(/\.hml$/, '');
    return base !== '' && base === v.file.toLowerCase();
  };

  const fileLabelOf = (v: ViewInfo): string => v.fileRelative || v.file;

  // 种子布局排序：当前文件优先 → 相对路径 → 名称
  const ordered = [...views].sort((a, b) => {
    const aCur = isCurrentFile(a);
    const bCur = isCurrentFile(b);
    if (aCur !== bCur) {
      return aCur ? -1 : 1;
    }
    const fileCmp = fileLabelOf(a).localeCompare(fileLabelOf(b));
    if (fileCmp !== 0) {
      return fileCmp;
    }
    return a.name.localeCompare(b.name);
  });

  const edges: ViewFlowEdge[] = [];
  const edgeIds = new Set<string>();
  // 占位节点：无效 / 歧义目标（保证每条 T2 边都可见）
  const synthetic = new Map<string, GraphSeed>();
  const invalidOutBy = new Map<string, number>();
  const ambiguousOutBy = new Map<string, number>();
  const seenNodeIds = new Set<string>();
  const seeds: GraphSeed[] = [];

  for (const view of ordered) {
    const id = nodeIdOf(view);
    if (seenNodeIds.has(id)) {
      continue; // 防御：复合键理论上唯一
    }
    seenNodeIds.add(id);
    seeds.push({
      id,
      data: {
        name: view.name,
        fileLabel: fileLabelOf(view),
        isCurrentFile: isCurrentFile(view),
        kind: 'view',
        invalidOut: 0,
        ambiguousOut: 0,
        autoId: isAutoGeneratedId(view.id),
      },
    });
  }

  for (const view of ordered) {
    const sourceId = nodeIdOf(view);
    (view.edges || []).forEach((e, ei) => {
      if (!e.target) {
        return;
      }
      const isTimer = e.sourceIsTimer === true || (e.eventType || e.event) === 'timer';
      const invalid = e.isValid === false;
      const ambiguous = e.targetAmbiguous === true;

      let targetNodeId: string;
      if (invalid) {
        targetNodeId = `missing:${e.target}`;
        invalidOutBy.set(sourceId, (invalidOutBy.get(sourceId) || 0) + 1);
      } else if (ambiguous || !e.targetViewKey) {
        // 歧义（或旧数据未解析出目标复合键）→ 歧义占位节点
        targetNodeId = `ambiguous:${e.target}`;
        ambiguousOutBy.set(sourceId, (ambiguousOutBy.get(sourceId) || 0) + 1);
      } else {
        targetNodeId = e.targetViewKey;
      }

      if (targetNodeId.startsWith('missing:') || targetNodeId.startsWith('ambiguous:')) {
        if (!synthetic.has(targetNodeId)) {
          synthetic.set(targetNodeId, {
            id: targetNodeId,
            data: {
              name: e.target,
              fileLabel: '',
              isCurrentFile: false,
              kind: targetNodeId.startsWith('missing:') ? 'missing' : 'ambiguous',
              invalidOut: 0,
              ambiguousOut: 0,
              autoId: false,
            },
          });
        }
      }

      // 边标签：触发控件 · 手势（定时器边标注"定时器触发"）；聚焦模式再拼接动画
      const controlPart = e.sourceIsView
        ? t('Screen')
        : (e.sourceControlName || e.sourceControlId || '');
      const triggerPart = isTimer ? t('Timer trigger') : eventLabel(e.eventType || e.event);
      const shortLabel = controlPart ? `${controlPart} · ${triggerPart}` : triggerPart;
      const expandedLabel = `${shortLabel} · ${animationLabelOf(e)}`;

      const color = invalid ? COLOR_INVALID : ambiguous ? COLOR_AMBIGUOUS : COLOR_VALID;
      let edgeId = e.edgeId || `${sourceId}->${e.target}@${ei}`;
      if (edgeIds.has(edgeId)) {
        edgeId = `${edgeId}@${ei}`;
      }
      edgeIds.add(edgeId);

      const classNames = ['vrm-edge'];
      if (invalid) {
        classNames.push('vrm-edge-invalid');
      } else if (ambiguous) {
        classNames.push('vrm-edge-ambiguous');
      }
      if (isTimer) {
        classNames.push('vrm-edge-timer');
      }

      // T11 编辑能力：定位字段齐全才可写（旧数据/快照缺失降级只读）；
      // 定时器边全程只读；歧义 target 禁止改目标（约束 4），允许删除
      const hasLocator = locatorOf(e) !== null;
      const canReconnect = hasLocator && !isTimer && !ambiguous;
      const canDelete = hasLocator && !isTimer;

      edges.push({
        id: edgeId,
        source: sourceId,
        target: targetNodeId,
        label: shortLabel,
        className: classNames.join(' '),
        // 只允许拖目标端改目标（源端由控件归属决定，不可改）
        reconnectable: canReconnect ? ('target' as const) : false,
        style: {
          stroke: color,
          strokeWidth: 1.5,
          opacity: OVERVIEW_EDGE_OPACITY_DEFAULT,
          ...(isTimer ? { strokeDasharray: '6 4' } : {}),
        },
        markerEnd: { type: MarkerType.ArrowClosed, color, width: 16, height: 16 },
        data: {
          sourceId,
          targetId: targetNodeId,
          isTimer,
          invalid,
          ambiguous,
          shortLabel,
          expandedLabel,
          raw: e,
          canReconnect,
          canDelete,
        },
      });
    });
  }

  // 回填出边告警计数
  for (const seed of seeds) {
    seed.data.invalidOut = invalidOutBy.get(seed.id) || 0;
    seed.data.ambiguousOut = ambiguousOutBy.get(seed.id) || 0;
  }

  // 占位节点殿后，按名称排序
  const syntheticSeeds = [...synthetic.values()].sort((a, b) => a.data.name.localeCompare(b.data.name));

  return {
    seeds: [...seeds, ...syntheticSeeds],
    edges,
    viewCount: views.length,
    edgeCount: edges.length,
  };
};

// 种子网格布局：≈√(1.6n) 列的紧凑网格（同文件 view 因排序相邻聚拢）
const GRID_CELL_W = 260;
const GRID_CELL_H = 130;

// 聚焦子图布局：左入右出（前驱居左，焦点居中，后继居右）
const FOCUS_COL_GAP = 340;
const FOCUS_ROW_GAP = 120;

const seedNodes = (
  seeds: GraphSeed[],
  savedPositions: Map<string, { x: number; y: number }>
): ViewFlowNode[] => {
  const cols = Math.max(1, Math.round(Math.sqrt(seeds.length * 1.6)));
  return seeds.map((seed, i) => ({
    id: seed.id,
    type: 'viewCard' as const,
    // T11：占位节点（missing/ambiguous）不可作为连接端点
    connectable: seed.data.kind === 'view',
    position: savedPositions.get(seed.id) || {
      x: (i % cols) * GRID_CELL_W,
      y: Math.floor(i / cols) * GRID_CELL_H,
    },
    data: seed.data,
  }));
};

const minimapNodeColor = (node: Node): string => {
  const data = node.data as ViewNodeData | undefined;
  if (data?.kind === 'missing') {
    return COLOR_INVALID;
  }
  if (data?.kind === 'ambiguous') {
    return COLOR_AMBIGUOUS;
  }
  if (data?.isCurrentFile) {
    return COLOR_CURRENT;
  }
  return COLOR_NODE_DEFAULT;
};

interface FocusView {
  nodes: ViewFlowNode[];
  edges: ViewFlowEdge[];
}

/** 焦点 + 直接前驱 + 直接后继 子图，左入右出布局 */
const buildFocusView = (
  focusId: string,
  seedById: Map<string, GraphSeed>,
  allEdges: ViewFlowEdge[]
): FocusView | null => {
  const focusSeed = seedById.get(focusId);
  if (!focusSeed) {
    return null;
  }

  const predecessorIds: string[] = [];
  const successorIds: string[] = [];
  const seenPred = new Set<string>();
  const seenSucc = new Set<string>();
  const relatedEdges = new Map<string, ViewFlowEdge>();

  for (const edge of allEdges) {
    const isIncoming = edge.target === focusId;
    const isOutgoing = edge.source === focusId;
    if (!isIncoming && !isOutgoing) {
      continue;
    }
    relatedEdges.set(edge.id, edge);
    if (isIncoming && edge.source !== focusId && !seenPred.has(edge.source)) {
      seenPred.add(edge.source);
      predecessorIds.push(edge.source);
    }
    if (isOutgoing && edge.target !== focusId && !seenSucc.has(edge.target)) {
      seenSucc.add(edge.target);
      successorIds.push(edge.target);
    }
  }

  // 同一邻居既是前驱又是后继时只放一列（左列）并标"双向"徽记：
  // 同一 id 出现在两列会产生重复节点 id，React Flow nodeLookup 去重后只渲染
  // 后注册的那份，左列该行空缺、前驱边反向画回交点。两条边都保留指向该节点。
  const successorOnlyIds = successorIds.filter(id => !seenPred.has(id));

  const nodes: ViewFlowNode[] = [];
  predecessorIds.forEach((id, i) => {
    const seed = seedById.get(id);
    if (!seed) {
      return;
    }
    const bidirectional = seenSucc.has(id);
    nodes.push({
      id,
      type: 'viewCard',
      connectable: seed.data.kind === 'view',
      position: { x: 0, y: i * FOCUS_ROW_GAP },
      data: bidirectional ? { ...seed.data, bidirectional: true } : seed.data,
    });
  });

  const centerRowCount = Math.max(predecessorIds.length, successorOnlyIds.length, 1);
  nodes.push({
    id: focusId,
    type: 'viewCard',
    connectable: focusSeed.data.kind === 'view',
    position: { x: FOCUS_COL_GAP, y: ((centerRowCount - 1) * FOCUS_ROW_GAP) / 2 },
    data: focusSeed.data,
  });

  successorOnlyIds.forEach((id, i) => {
    const seed = seedById.get(id);
    if (!seed) {
      return;
    }
    nodes.push({
      id,
      type: 'viewCard',
      connectable: seed.data.kind === 'view',
      position: { x: FOCUS_COL_GAP * 2, y: i * FOCUS_ROW_GAP },
      data: seed.data,
    });
  });

  const edges: ViewFlowEdge[] = [...relatedEdges.values()].map(edge => ({
    ...edge,
    label: edge.data?.expandedLabel ?? edge.label,
  }));

  return { nodes, edges };
};

