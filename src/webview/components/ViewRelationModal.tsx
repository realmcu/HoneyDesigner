// ---------------- 节点数据模型 ----------------

type ViewNodeKind = 'view' | 'missing' | 'ambiguous';

interface ViewNodeData extends Record<string, unknown> {
  name: string;
  fileLabel: string;      // 文件相对路径（T2 fileRelative；旧数据回退 basename）
  isCurrentFile: boolean;
  kind: ViewNodeKind;     // view=真实屏；missing=无效目标占位；ambiguous=歧义目标占位
  invalidOut: number;     // 出边中无效目标条数
  ambiguousOut: number;   // 出边中歧义目标条数
  autoId: boolean;        // id 为解析器自动生成（建议补显式 id）
  bidirectional?: boolean; // 聚焦子图中既是前驱又是后继（只放左列并标徽记，渲染期计算）
}

type ViewFlowNode = Node<ViewNodeData, 'viewCard'>;

// ---------------- 边数据模型 ----------------

interface ViewEdgeData extends Record<string, unknown> {
  sourceId: string;
  targetId: string;
  isTimer: boolean;
  invalid: boolean;
  ambiguous: boolean;
  shortLabel: string;    // 全局图标签：触发控件 · 手势
  expandedLabel: string; // 聚焦模式标签：触发控件 · 事件 · 动画
  raw: ViewEdgeInfo;     // T2 原始边数据（T11 编辑定位用）
  canReconnect: boolean; // 可拖目标端改跳转（非定时器、非歧义、定位字段齐全）
  canDelete: boolean;    // 可删除（非定时器、定位字段齐全）
}

type ViewFlowEdge = Edge<ViewEdgeData>;

